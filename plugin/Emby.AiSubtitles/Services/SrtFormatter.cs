using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Emby.AiSubtitles.Configuration;
using Emby.AiSubtitles.Models;

namespace Emby.AiSubtitles.Services
{
    public static class SrtFormatter
    {
        public static string NormalizeFormat(string format)
        {
            return string.Equals(format, "srt", StringComparison.OrdinalIgnoreCase) ? "srt" : "ass";
        }

        public static string Build(IList<SubtitleCue> cues, PluginConfiguration config, bool bilingual)
        {
            var format = NormalizeFormat(config?.SubtitleFormat);
            var primaryColor = NormalizeHexColor(config?.PrimaryTextColor, "#FFFFFF");
            var secondaryColor = NormalizeHexColor(config?.SecondaryTextColor, "#FFD700");

            return format == "ass"
                ? BuildAss(cues, bilingual, primaryColor, secondaryColor)
                : BuildSrt(cues, bilingual, primaryColor, secondaryColor);
        }

        /// <summary>
        /// 生成 ASS 特效字幕：
        /// - 强制底部居中（Alignment = 2），绝不会跑到屏幕顶部
        /// - 单条 Dialogue 内用 \N 换行 + 内联样式切换，确保所有播放器都把两行作为整体放在屏幕最下方
        /// - 第一行中文/译文（白色、大字号 56），第二行英文/原文（黄色、小字号 40）
        /// </summary>
        public static string BuildAss(IList<SubtitleCue> cues, bool bilingual, string primaryHex, string secondaryHex)
        {
            var primaryAss = ToAssStyleColor(primaryHex);
            var secondaryAss = ToAssStyleColor(secondaryHex);
            var secondaryInline = ToAssInlineColor(secondaryHex);

            var sb = new StringBuilder();
            sb.AppendLine("[Script Info]");
            sb.AppendLine("; Script generated by Emby.AiSubtitles");
            sb.AppendLine("ScriptType: v4.00+");
            sb.AppendLine("PlayResX: 1920");
            sb.AppendLine("PlayResY: 1080");
            sb.AppendLine("WrapStyle: 0");
            sb.AppendLine("ScaledBorderAndShadow: yes");
            sb.AppendLine();
            sb.AppendLine("[V4+ Styles]");
            sb.AppendLine("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding");
            // Alignment=2 表示底部居中（Bottom-Center），MarginV=45 距离底边 45 像素
            sb.AppendFormat(CultureInfo.InvariantCulture,
                "Style: Default,sans-serif,56,{0},&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,2.5,1.2,2,30,30,45,1\n",
                primaryAss);
            sb.AppendFormat(CultureInfo.InvariantCulture,
                "Style: Secondary,sans-serif,40,{0},&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,2.0,1.0,2,30,30,45,1\n",
                secondaryAss);
            sb.AppendLine();
            sb.AppendLine("[Events]");
            sb.AppendLine("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text");

            foreach (var cue in cues)
            {
                var original = EscapeAss(Clean(cue.Text));
                var translated = EscapeAss(Clean(cue.Translation));

                if (string.IsNullOrWhiteSpace(translated) && string.IsNullOrWhiteSpace(original))
                {
                    continue;
                }

                string body;
                if (string.IsNullOrEmpty(translated))
                {
                    body = original;
                }
                else if (bilingual && !string.Equals(original, translated, StringComparison.Ordinal) && !string.IsNullOrEmpty(original))
                {
                    // {\an2} 再次显式锁定底部居中；第一行中文（白色 56 号），\N 换行后第二行英文（黄色 40 号）
                    body = string.Format(CultureInfo.InvariantCulture,
                        "{{\\an2}}{0}\\N{{\\rSecondary\\fs40\\1c{1}}}{2}",
                        translated, secondaryInline, original);
                }
                else
                {
                    body = "{\\an2}" + translated;
                }

                if (string.IsNullOrWhiteSpace(body) || body == "{\\an2}")
                {
                    continue;
                }

                var start = FormatAssTime(cue.Start);
                var end = FormatAssTime(Math.Max(cue.End, cue.Start + 0.3));
                sb.AppendFormat(CultureInfo.InvariantCulture, "Dialogue: 0,{0},{1},Default,,0,0,0,,{2}\n", start, end, body);
            }

            return sb.ToString();
        }

        /// <summary>
        /// 生成带颜色和底部定位标签的 SRT 字幕：
        /// - 顶部加 {\an2} 锁定底部居中，防止播放器将双行字幕拆到屏幕顶端
        /// - 中文使用白色 &lt;font color="#FFFFFF"&gt;，英文使用黄色 &lt;font color="#FFD700"&gt;
        /// </summary>
        public static string BuildSrt(IList<SubtitleCue> cues, bool bilingual, string primaryHex, string secondaryHex)
        {
            var sb = new StringBuilder();
            var index = 1;
            foreach (var cue in cues)
            {
                var original = Clean(cue.Text);
                var translated = Clean(cue.Translation);
                string body;
                if (string.IsNullOrEmpty(translated))
                {
                    body = string.Format(CultureInfo.InvariantCulture, "<font color=\"{0}\">{1}</font>", primaryHex, original);
                }
                else if (bilingual && !string.Equals(original, translated, StringComparison.Ordinal) && !string.IsNullOrEmpty(original))
                {
                    body = string.Format(CultureInfo.InvariantCulture,
                        "<font color=\"{0}\">{1}</font>\n<font color=\"{2}\">{3}</font>",
                        primaryHex, translated, secondaryHex, original);
                }
                else
                {
                    body = string.Format(CultureInfo.InvariantCulture, "<font color=\"{0}\">{1}</font>", primaryHex, translated);
                }

                if (string.IsNullOrWhiteSpace(original) && string.IsNullOrWhiteSpace(translated))
                {
                    continue;
                }

                sb.Append(index++).Append('\n');
                sb.Append(FormatSrtTime(cue.Start))
                  .Append(" --> ")
                  .Append(FormatSrtTime(Math.Max(cue.End, cue.Start + 0.3)))
                  .Append('\n');
                sb.Append(body).Append("\n\n");
            }

            return sb.ToString();
        }

        /// <summary>字幕生成期间先交给 Emby 保存的占位字幕。</summary>
        public static string Placeholder(string message, string format = "ass")
        {
            if (NormalizeFormat(format) == "ass")
            {
                var cues = new List<SubtitleCue>
                {
                    new SubtitleCue { Start = 1, End = 15, Text = message }
                };
                return BuildAss(cues, false, "#FFFFFF", "#FFD700");
            }

            return "1\n00:00:01,000 --> 00:00:15,000\n" + message + "\n\n";
        }

        private static readonly Regex SrtTimeRegex = new Regex(
            @"^(\d{1,2}):(\d{2}):(\d{2})[,.](\d{1,3})\s*-->\s*(\d{1,2}):(\d{2}):(\d{2})[,.](\d{1,3})",
            RegexOptions.Compiled);

        private static readonly Regex InlineTagStripRegex = new Regex(
            @"\{[^}]*\}|<[^>]*>",
            RegexOptions.Compiled);

        /// <summary>
        /// 解析标准 SRT 字幕文本为 SubtitleCue 列表，自动清除旧定位标签、水印和无意义语气词，便于统一转换为底部对齐 ASS 字幕。
        /// </summary>
        public static List<SubtitleCue> ParseSrt(string srtContent, bool filterFillerSounds = true)
        {
            var result = new List<SubtitleCue>();
            if (string.IsNullOrWhiteSpace(srtContent))
            {
                return result;
            }

            var lines = srtContent.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
            int i = 0;
            while (i < lines.Length)
            {
                var line = lines[i].Trim();
                var m = SrtTimeRegex.Match(line);
                if (!m.Success)
                {
                    i++;
                    continue;
                }

                double start = ParseTimeParts(m.Groups[1].Value, m.Groups[2].Value, m.Groups[3].Value, m.Groups[4].Value);
                double end = ParseTimeParts(m.Groups[5].Value, m.Groups[6].Value, m.Groups[7].Value, m.Groups[8].Value);
                i++;

                var textLines = new List<string>();
                while (i < lines.Length && !string.IsNullOrWhiteSpace(lines[i]))
                {
                    // 如果下一行已经是新的时间戳，跳出
                    if (SrtTimeRegex.IsMatch(lines[i].Trim()))
                    {
                        break;
                    }

                    // 看看是不是下一段的序号（紧接着下一行是时间戳）
                    if (i + 1 < lines.Length && int.TryParse(lines[i].Trim(), out _) && SrtTimeRegex.IsMatch(lines[i + 1].Trim()))
                    {
                        break;
                    }

                    var cleaned = InlineTagStripRegex.Replace(lines[i], string.Empty).Trim();
                    if (!string.IsNullOrWhiteSpace(cleaned) && !IsWatermarkCreditLine(cleaned, start))
                    {
                        textLines.Add(cleaned);
                    }
                    i++;
                }

                if (textLines.Count == 0)
                {
                    continue;
                }

                string primaryLine = textLines[0];
                string secondaryLine = textLines.Count > 1 ? string.Join(" ", textLines.GetRange(1, textLines.Count - 1)) : string.Empty;

                if (filterFillerSounds && SubtitleFilter.IsFillerOrMoan(primaryLine) &&
                    (string.IsNullOrEmpty(secondaryLine) || SubtitleFilter.IsFillerOrMoan(secondaryLine)))
                {
                    continue;
                }

                result.Add(new SubtitleCue
                {
                    Start = start,
                    End = Math.Max(end, start + 0.5),
                    Translation = primaryLine,
                    Text = secondaryLine
                });
            }

            return result;
        }

        private static bool IsWatermarkCreditLine(string text, double startSeconds)
        {
            if (startSeconds > 30)
            {
                return false;
            }

            return text.IndexOf("字幕制作", StringComparison.OrdinalIgnoreCase) >= 0 ||
                   text.IndexOf("Mimomoomime", StringComparison.OrdinalIgnoreCase) >= 0 ||
                   text.IndexOf("Jamakav", StringComparison.OrdinalIgnoreCase) >= 0 ||
                   text.IndexOf("subtitlecat", StringComparison.OrdinalIgnoreCase) >= 0;
        }

        private static double ParseTimeParts(string h, string m, string s, string ms)
        {
            int hours = int.TryParse(h, out var hh) ? hh : 0;
            int mins = int.TryParse(m, out var mm) ? mm : 0;
            int secs = int.TryParse(s, out var ss) ? ss : 0;
            ms = ms.PadRight(3, '0').Substring(0, 3);
            int millis = int.TryParse(ms, out var mss) ? mss : 0;
            return hours * 3600.0 + mins * 60.0 + secs + millis / 1000.0;
        }

        private static string NormalizeHexColor(string hex, string fallback)
        {
            if (string.IsNullOrWhiteSpace(hex))
            {
                return fallback;
            }

            hex = hex.Trim();
            if (!hex.StartsWith("#", StringComparison.Ordinal))
            {
                hex = "#" + hex;
            }

            if (hex.Length == 7)
            {
                return hex.ToUpperInvariant();
            }

            return fallback;
        }

        /// <summary>#RRGGBB -> &amp;H00BBGGRR（ASS Style 表颜色格式）。</summary>
        private static string ToAssStyleColor(string hex)
        {
            var r = hex.Substring(1, 2);
            var g = hex.Substring(3, 2);
            var b = hex.Substring(5, 2);
            return string.Format(CultureInfo.InvariantCulture, "&H00{0}{1}{2}", b, g, r);
        }

        /// <summary>#RRGGBB -> &amp;HBBGGRR&amp;（ASS 内联 \1c 颜色格式）。</summary>
        private static string ToAssInlineColor(string hex)
        {
            var r = hex.Substring(1, 2);
            var g = hex.Substring(3, 2);
            var b = hex.Substring(5, 2);
            return string.Format(CultureInfo.InvariantCulture, "&H{0}{1}{2}&", b, g, r);
        }

        private static string EscapeAss(string text)
        {
            if (string.IsNullOrEmpty(text))
            {
                return string.Empty;
            }

            return text
                .Replace("{", "（")
                .Replace("}", "）")
                .Replace("\n", "\\N");
        }

        private static string Clean(string text)
        {
            return string.IsNullOrWhiteSpace(text) ? string.Empty : text.Replace("\r", string.Empty).Trim();
        }

        private static string FormatSrtTime(double seconds)
        {
            if (seconds < 0)
            {
                seconds = 0;
            }

            var t = TimeSpan.FromMilliseconds(Math.Round(seconds * 1000));
            return string.Format(CultureInfo.InvariantCulture, "{0:00}:{1:00}:{2:00},{3:000}",
                (int)t.TotalHours, t.Minutes, t.Seconds, t.Milliseconds);
        }

        private static string FormatAssTime(double seconds)
        {
            if (seconds < 0)
            {
                seconds = 0;
            }

            var totalCentiseconds = (int)Math.Round(seconds * 100);
            var cs = totalCentiseconds % 100;
            var totalSeconds = totalCentiseconds / 100;
            var s = totalSeconds % 60;
            var totalMinutes = totalSeconds / 60;
            var m = totalMinutes % 60;
            var h = totalMinutes / 60;
            return string.Format(CultureInfo.InvariantCulture, "{0}:{1:00}:{2:00}.{3:00}", h, m, s, cs);
        }
    }
}
